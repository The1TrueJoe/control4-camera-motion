#!/usr/bin/env bash
# Builds camera_motion.c4z into dist/.
#
# The driver's Lua is the files in src/ concatenated in filename order into driver/driver.lua,
# syntax-checked as Lua 5.1, version-stamped, and zipped with driver.xml and www/. A .c4z is a
# plain zip; no packager is needed for an unencrypted driver.
# Requires: luajit (or luac), zip, git (optional, for the version number)
set -euo pipefail

cd "$(dirname "$0")"
VERSION=$(git rev-list --count HEAD 2>/dev/null || echo 1)
BUILD_DATE=$(date +"%m/%d/%Y %H:%M")
mkdir -p dist

check_lua() {
  if command -v luajit >/dev/null; then
    luajit -bl "$1" >/dev/null
  elif command -v luac5.1 >/dev/null; then
    luac5.1 -p "$1"
  elif command -v luac >/dev/null; then
    luac -p "$1"
  else
    echo "warning: no luajit/luac found, skipping syntax check" >&2
  fi
}

out="driver/driver.lua"
{
  echo "-- NVR Camera Motion driver for Control4."
  echo "-- AUTO-GENERATED by build.sh — edit src/ instead."
  echo '---@diagnostic disable: undefined-global'
  for f in src/*.lua; do
    echo
    echo "-- ${f}"
    sed "s/^DRIVER_VERSION = .*/DRIVER_VERSION = '${VERSION}'/" "$f"
  done
} > "$out"
check_lua "$out"

# Stamp a staging copy so building never leaves driver.xml modified in git.
stage=$(mktemp -d)
cp -R driver/driver.xml "$out" www "$stage/"
sed -i '' "s|<modified>.*</modified>|<modified>${BUILD_DATE}</modified>|" "$stage/driver.xml" 2>/dev/null \
  || sed -i "s|<modified>.*</modified>|<modified>${BUILD_DATE}</modified>|" "$stage/driver.xml"
sed -i '' "s|<version>[^<]*</version>|<version>${VERSION}</version>|" "$stage/driver.xml" 2>/dev/null \
  || sed -i "s|<version>[^<]*</version>|<version>${VERSION}</version>|" "$stage/driver.xml"

c4z="dist/camera_motion.c4z"
rm -f "$c4z"
(cd "$stage" && zip -qr "$OLDPWD/$c4z" driver.xml driver.lua www)
rm -rf "$stage"
echo "built $c4z (version $VERSION, $(wc -l < "$out" | tr -d ' ') lines of Lua)"
